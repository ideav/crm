#!/usr/bin/env bash
# Запрет НОВЫХ проверок по ТЕКСТУ ИСХОДНИКА (issue #4751, разбор порочного круга).
#
# ЗАЧЕМ. Утверждение вида `assert(/что-то/.test(src))` или `assert(src.match(/…/g).length === N)`
# проверяет не поведение, а НАПИСАНИЕ кода. У такой проверки два свойства, и оба вредны:
#   • она МОЛЧИТ, когда поведение сломано. Боевой пример: `atex-pp-4631` считал вхождения
#     `self.reconcileSleeveTasks(` и требовал ровно два. Число сходилось, а путь удаления ДНЯ
#     разбор не звал вовсе, и оба пути удаления падали `ReferenceError` (issue #4753);
#   • она КРАСНЕЕТ от любого рефакторинга — и тогда её правит автор соседнего фикса, подгоняя
#     число под себя. `atex-pp-4743` переписывали так дважды подряд (#4745, затем #4749), и
#     ожидание переставало быть оракулом.
# Ровно этим держался цикл из десяти тикетов про «день не набит» (#4469 → #4751).
#
# ЧТО СЧИТАЕТСЯ НАРУШЕНИЕМ. Строка-утверждение, чьё условие опирается на текст файла, прочитанного
# через `readFileSync`, либо на `.toString()` функции. ЧИТАТЬ исходник можно и нужно — многие
# браузерные файлы не являются CommonJS-модулями и загружаются чтением + `eval`; запрещено именно
# УТВЕРЖДАТЬ о его тексте.
#
# ГДЕ ПРОВЕРЯЕТСЯ. Только в тестах, ДОБАВЛЕННЫХ ИЛИ ИЗМЕНЁННЫХ этим PR, и только по СТРОКАМ,
# которые PR добавил. Существующие проверки не трогаются: их около сорока, сплошная переделка
# задела бы десятки чужих тикетов и ничего бы не доказала. Правило работает вперёд — «новых не
# заводим», и список сокращается по мере того, как файлы правят по своим причинам.
#
# КАК РАЗРЕШИТЬ ЗАКОННЫЙ СЛУЧАЙ. Он бывает: проверить, что в HTML подключён задеплоенный ассет,
# иначе как по тексту нельзя. Тогда в теле PR или в сообщении коммита пишется строка:
#     TEXT-ASSERT-OK: <почему поведением проверить нельзя>
# Как и `RATCHET-OK`, это не формальность: исключение становится ЗАЯВЛЕННЫМ и попадает в ревью.
#
# Использование:
#   bash scripts/check-text-assertions.sh [<base-ref>]    # по умолчанию origin/main
# В CI разрешающая строка берётся ещё и из переменной TEXT_ASSERT_DECLARATION (тело PR).
set -uo pipefail
cd "$(dirname "$0")/.."

BASE="${1:-origin/main}"
git rev-parse --verify "$BASE" >/dev/null 2>&1 || { echo "нет базовой ветки $BASE — проверка пропущена"; exit 0; }
MERGE_BASE="$(git merge-base "$BASE" HEAD 2>/dev/null || echo "$BASE")"

TEST_RE='(\.test\.js|-test\.js|_test\.js)$|^experiments/test-.*\.js$'

mapfile -t files < <(git diff --diff-filter=AM --name-only "$MERGE_BASE"...HEAD -- 'experiments/*' \
    | grep -E "$TEST_RE" || true)
if [[ ${#files[@]} -eq 0 ]]; then echo "тестов в изменениях нет — проверять нечего"; exit 0; fi

# Утверждение о ТЕКСТЕ: assert…( … <переменная-исходник> … .test( | .match( | indexOf( | includes( )
# либо assert( /…/.test(src) ). Имена переменных-исходников по факту сложившиеся в репозитории.
SRC_VAR='(src|source|code|html|css|text|body|content|file)'
ASSERT_RE="assert[A-Za-z]*\(.*(\b${SRC_VAR}\b.*(\.test\(|\.match\(|\.indexOf\(|\.includes\()|/.*/\.test\(\s*${SRC_VAR}\s*\))"

hits=()
for f in "${files[@]}"; do
  [[ -f "$f" ]] || continue
  # Только ДОБАВЛЕННЫЕ строки этого PR (префикс '+' в диффе, без заголовка '+++').
  while IFS= read -r line; do
    body="${line:1}"
    if grep -qE "$ASSERT_RE" <<<"$body"; then
      hits+=("$f: ${body:0:150}")
    fi
  # `-E` обязателен В ОБОИХ grep: в BRE `\+` — квантификатор «один и более», и фильтр
  # `grep -v '^\+\+\+'` выбрасывал бы ВСЕ строки, а проверка молча ничего не находила.
  done < <(git diff "$MERGE_BASE"...HEAD -- "$f" | grep -aE '^\+' | grep -avE '^\+\+\+' || true)
done

if [[ ${#hits[@]} -eq 0 ]]; then echo "новых проверок по тексту исходника нет ✓"; exit 0; fi

# Разрешение ищется ТОЛЬКО по строке `TEXT-ASSERT-OK:` — в сообщениях коммитов PR либо в его теле.
# Раньше в `DECL` сперва клали ТЕЛО PR целиком, а ниже проверяли его на непустоту: любой PR с
# непустым описанием проходил проверку молча (боевое — PR #4771: «TEXT-ASSERT-OK найдено (<всё тело
# PR>) — исключение заявлено, пропускаю»). Проверка была выключена для всех PR, у которых есть текст.
DECL=""
if git log "$MERGE_BASE"..HEAD --format='%B' 2>/dev/null | grep -q 'TEXT-ASSERT-OK:'; then DECL="объявлено в коммите"; fi
if grep -q 'TEXT-ASSERT-OK:' <<<"${TEXT_ASSERT_DECLARATION:-}"; then DECL="объявлено в PR"; fi

echo "НОВЫЕ проверки по ТЕКСТУ ИСХОДНИКА (${#hits[@]}):"
printf '  %s\n' "${hits[@]}"
echo
if [[ -n "$DECL" ]]; then
  echo "TEXT-ASSERT-OK найдено ($DECL) — исключение заявлено, пропускаю."
  exit 0
fi
echo "Проверяйте ПОВЕДЕНИЕ, а не написание кода: прогоните код и утверждайте о результате."
echo "Если поведением нельзя (например, ассет подключён в HTML) — впишите в тело PR строку:"
echo "    TEXT-ASSERT-OK: <почему поведением проверить нельзя>"
exit 1
