#!/usr/bin/env bash
# Храповик регрессионной сети (issue #4515): ОСЛАБЛЕНИЕ ожидания существующего теста не проходит
# молча.
#
# ЗАЧЕМ. Гейт не может покраснеть, если тест-оракул правится тем же PR, что и код. За 36 коммитов
# после появления гейта правки ожиданий получили 21 уже существовавший тест-файл;
# `atex-pp-4461-fixed-day-position.test.js` переписан трижды (#4481, #4487, #4497 — последний
# −49/+54). Гейт при этом зелёный, а правило «🔒 держит день» вернулось тикетом с ДОСЛОВНО тем же
# заголовком (#4463 → #4489). Тест, чьё ожидание меняет автор фикса, перестаёт быть оракулом.
#
# ЧТО СЧИТАЕТСЯ ОСЛАБЛЕНИЕМ. Два случая в ФАЙЛЕ, КОТОРЫЙ УЖЕ БЫЛ в базовой ветке:
#   • удалённая или изменённая строка-утверждение (assert / strictEqual / deepStrictEqual / ok( /
#     throws / expect);
#   • УДАЛЁНИЕ ФАЙЛА ЦЕЛИКОМ — сильнейшее ослабление, теряются все его утверждения сразу.
# Новый тест-файл — не ослабление (сеть растёт, это норма). Добавленные утверждения в старом файле —
# тоже норма.
#
# КАК РАЗРЕШИТЬ ЗАКОННОЕ ОСЛАБЛЕНИЕ. Ожидание действительно бывает устаревшим (правило изменил
# заказчик). Тогда в теле PR или в сообщении коммита пишется строка:
#     RATCHET-OK: <почему ожидание было неверным и чьим решением изменено>
# Это не формальность: она попадает в историю и в ревью — ослабление становится ЗАЯВЛЕННЫМ, а не
# случайным следствием фикса соседнего тикета.
#
# Использование:
#   bash scripts/check-test-ratchet.sh [<base-ref>]     # по умолчанию origin/main
# В CI разрешающая строка берётся ещё и из переменной RATCHET_DECLARATION (тело PR).
set -uo pipefail
cd "$(dirname "$0")/.."

BASE="${1:-origin/main}"
git rev-parse --verify "$BASE" >/dev/null 2>&1 || { echo "нет базовой ветки $BASE — проверка пропущена"; exit 0; }

MERGE_BASE="$(git merge-base "$BASE" HEAD 2>/dev/null || echo "$BASE")"

TEST_RE='(\.test\.js|-test\.js|_test\.js)$|^experiments/test-.*\.js$'

# Тестовые файлы, ИЗМЕНЁННЫЕ (не добавленные) относительно базы.
mapfile -t changed < <(git diff --diff-filter=M --name-only "$MERGE_BASE"...HEAD -- 'experiments/*' \
    | grep -E "$TEST_RE" || true)

# УДАЛЁННЫЕ целиком. Это сильнейшее ослабление сети — сильнее правки ожидания, — и по
# `CLAUDE.md` удаление устаревшего теста законно, но обязано быть ОБЪЯВЛЕНО с причиной. Первая
# версия храповика смотрела только на `M`, поэтому `git rm` тест-файла проходил молча: дыра
# нашлась при первом же разборе карантина (#4515).
mapfile -t deleted < <(git diff --diff-filter=D --name-only "$MERGE_BASE"...HEAD -- 'experiments/*' \
    | grep -E "$TEST_RE" || true)

if [[ ${#changed[@]} -eq 0 && ${#deleted[@]} -eq 0 ]]; then
  echo "храповик: изменённых и удалённых тестов нет — проверять нечего"
  exit 0
fi

ASSERT_RE='assert|strictEqual|deepStrictEqual|notEqual|\bok\(|throws|expect'

weakened=()
for f in "${deleted[@]}"; do
  # У удалённого файла ослаблены ВСЕ его утверждения.
  gone=$(git show "$MERGE_BASE:$f" 2>/dev/null | grep -cE "$ASSERT_RE" || true)
  weakened+=("$f (файл удалён целиком):${gone:-?}")
done
for f in "${changed[@]}"; do
  # Удалённые строки-утверждения (изменённая строка = удалённая + добавленная, ловится тем же).
  removed=$(git diff "$MERGE_BASE"...HEAD -- "$f" | grep -E "^-[^-]" | grep -cE "$ASSERT_RE" || true)
  if [[ "${removed:-0}" -gt 0 ]]; then
    weakened+=("$f:$removed")
  fi
done

if [[ ${#weakened[@]} -eq 0 ]]; then
  echo "храповик: ${#changed[@]} изменено, ${#deleted[@]} удалено; ожидания только добавлены — ослаблений нет"
  exit 0
fi

# Разрешение: тело PR (CI) или любое сообщение коммита в диапазоне.
declaration="${RATCHET_DECLARATION:-}"
commits_msg="$(git log --format='%B' "$MERGE_BASE"..HEAD 2>/dev/null || true)"
if grep -qE '^\s*RATCHET-OK:\s*\S' <<<"$declaration$commits_msg"; then
  echo "храповик: ослабление ЗАЯВЛЕНО (RATCHET-OK) — пропускаю"
  printf '  %s\n' "${weakened[@]}"
  exit 0
fi

echo "═══ ХРАПОВИК: ослаблены ожидания существующих тестов ═══"
# Без word-splitting: в записях про удаление есть пробелы и скобки.
for w in "${weakened[@]}"; do
  echo "  ${w%:*} — утверждений потеряно: ${w##*:}"
done
cat <<'MSG'

Тест, чьё ожидание меняет автор фикса, перестаёт быть оракулом: именно так правило «🔒 держит
день» вернулось тикетом с тем же заголовком (#4463 → #4489) через зелёный гейт.

Что делать:
  • ожидание было ВЕРНЫМ  → починить код, а не тест;
  • ожидание УСТАРЕЛО     → добавить в тело PR строку с причиной и чьим решением:
        RATCHET-OK: правило изменено заказчиком <дата> — <что и почему>
MSG
exit 1
