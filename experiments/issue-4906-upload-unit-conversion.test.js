// Regression test for issue #4906.
//
// Универсальный импорт («Загрузка данных», templates/upload.html) считает поле
// «Заказанное количество» (1076) формулой из настройки импорта («Настройка» 269,
// семейство «Заказы из 1С»): тыс. пог. м и пог. м делятся на длину из «Вида сырья».
//
// Заказ 5243: 21,96 тыс. пог. м при ролике 305 м — это 72 шт. Импорт записал 22,
// потому что регулярка единицы требовала РОВНО «тыс. пог. м», а 1С прислал
// «тыс.пог.м.» — без пробелов и с точкой в конце. Обе точки в «тыс.» и «пог.»
// регдулярка допускала только с \s* между ними, хвостовая точка после «м» — никак.
// Делитель уходил в fallback 1 → Math.ceil(21.96) = 22.
//
// Формулы живут в базе (реквизит 273 записей «Настройки» 269: 66419, 130866,
// 743249), в репозитории их не существует. Этот тест — исполняемая спецификация
// ПОЛЕЙ формулы: он держит старое и новое выражения и прогоняет их ровно так,
// как это делает страница импорта (подстановка сырых значений ячеек + eval,
// templates/upload.html:1332-1348). Правка формул в базе — docs/scripts/fix_4906_unit_regex.py.
//
// До правки тест красный: OLD даёт 22 на строке заказа 5243 (ожидаем 72).

var fs = require('fs');
var path = require('path');

var passed = 0, failed = 0;
function check(name, ok, extra){
  console.log((ok ? 'PASS' : 'FAIL') + ' — ' + name + (ok ? '' : ' — ' + extra));
  if (ok) passed++; else { failed++; process.exitCode = 1; }
}

// ── Формулы: старое и новое выражения полей 1076 и 136894 ────────────────────
// Разница — только в двух регулярках единицы: точки после «тыс»/«пог»/«м»
// необязательны (\.? — «тыс.пог.м.», «тыс. пог. м», «тыс пог м» — всё это одна
// единица). Прочее выражение не тронуто.

var F1076_OLD = "'[Срок изготовления]'===''?'':Math.ceil([Заказанное количество] / (/^тыс\\.\\s*пог\\.\\s*м$/i.test('[Ед.изм.]') ? +('[Вид сырья]'.replace(/^Образец\\s*/i, '').match(/\\d+\\s*[хx×*]\\s*(\\d+)/)?.[1]) / 1000 : /^пог\\.\\s*м$/i.test('[Ед.изм.]') ? +('[Вид сырья]'.replace(/^Образец\\s*/i, '').match(/\\d+\\s*[хx×*]\\s*(\\d+)/)?.[1]) : 1))";

var F1076_NEW = "'[Срок изготовления]'===''?'':Math.ceil([Заказанное количество] / (/^тыс\\.?\\s*пог\\.?\\s*м\\.?$/i.test('[Ед.изм.]') ? +('[Вид сырья]'.replace(/^Образец\\s*/i, '').match(/\\d+\\s*[хx×*]\\s*(\\d+)/)?.[1]) / 1000 : /^пог\\.?\\s*м\\.?$/i.test('[Ед.изм.]') ? +('[Вид сырья]'.replace(/^Образец\\s*/i, '').match(/\\d+\\s*[хx×*]\\s*(\\d+)/)?.[1]) : 1))";

var F136894_OLD = "/^тыс\\.\\s*пог\\.\\s*м$/i.test('[Ед.изм.]') ? [Заказанное количество] * 1000 : /^пог\\.\\s*м$/i.test('[Ед.изм.]') ? [Заказанное количество] : ''";

var F136894_NEW = "/^тыс\\.?\\s*пог\\.?\\s*м\\.?$/i.test('[Ед.изм.]') ? [Заказанное количество] * 1000 : /^пог\\.?\\s*м\\.?$/i.test('[Ед.изм.]') ? [Заказанное количество] : ''";

var F129370 = "'шт'";

// ── Исполнение ровно как на странице импорта ─────────────────────────────────
// serializeUploadCellValue и escapeFormulaValue — из templates/upload.html
// (637-649, 703-713); подстановка плейсхолдеров — 1332-1337; значение поля
// строки — raw-ячейка файла, приводится к строке как есть.

function serializeUploadCellValue(v){
  if(v===undefined||v===null) return '';
  if(typeof v==='object'){ try{ return JSON.stringify(v); }catch(e){ return String(v); } }
  return v.toString();
}
function escapeFormulaValue(v){
  return String(v===undefined||v===null?'':v)
    .replace(/\\/g,'\\\\')
    .replace(/'/g,"\\'")
    .replace(/"/g,'\\"')
    .replace(/`/g,'\\`')
    .replace(/\r/g,'\\r')
    .replace(/\n/g,'\\n')
    .replace(new RegExp(String.fromCharCode(0x2028),'g'),'\\u2028')
    .replace(new RegExp(String.fromCharCode(0x2029),'g'),'\\u2029');
}
// row: {«Имя колонки файла»: значение}; возвращает вычисленные поля как строку (как в toImport).
function evalFormulas(formulas, row){
  var out = {};
  for (var id in formulas){
    var expr = formulas[id].replace(/\[(.+?)\]/mug, function($1, $2){
      if ($2 in row) return escapeFormulaValue(row[$2]);
      return $1; // не плейсхолдер (например, [хx×*] внутри regex-литерала) — как на странице
    });
    try { out[id] = serializeUploadCellValue(eval(expr)); }
    catch(e) { out[id] = 'EVAL ERROR: ' + e.message; }
  }
  return out;
}

var NEW_FORMULAS = { '1076': F1076_NEW, '129370': F129370, '136894': F136894_NEW };
var OLD_FORMULAS = { '1076': F1076_OLD, '136894': F136894_OLD };

// ── Строка заказа 5243 из файла 1С ────────────────────────────────────────────
// «Фольга горячего тиснения MВ 50 х 305 IN» — ролик 305 м; количество 21,96
// тыс. пог. м = 21960 м = 72 ролика. Единица — как прислал 1С: «тыс.пог.м.».
var row5243 = {
  'Примечание': '5243 / Фольга горячего тиснения MВ 50 х 305 IN в тыс.метрах (П) / 49мм x 18 / 4 резок (882мм)',
  'Вид сырья': 'Фольга горячего тиснения MВ 50 х 305 IN',
  'Ширина, мм': '49',
  'Длина, м': '305',
  'Срок изготовления': '11.09.2026',
  'Ед.изм.': 'тыс.пог.м.',
  'Заказанное количество': 21.96
};

var r = evalFormulas(NEW_FORMULAS, row5243);
check('5243: 21,96 тыс.пог.м. при ролике 305 м → 72 шт (было 22)', r['1076'] === '72', r['1076']);
check('5243: «Заказано в метрах» = 21960 (было пусто)', r['136894'] === '21960', r['136894']);
check('5243: «Ед.изм.» = шт', r['129370'] === 'шт', r['129370']);

// ── Все написания одной единицы дают один результат ──────────────────────────
['тыс.пог.м.', 'тыс.пог.м', 'тыс. пог. м', 'тыс пог м', 'Тыс. Пог. М.'].forEach(function(u){
  var row = Object.assign({}, row5243, {'Ед.изм.': u});
  var got = evalFormulas(NEW_FORMULAS, row);
  check('написание единицы «' + u + '» → 72 шт', got['1076'] === '72', got['1076']);
});

// ── Прочие единицы ведут себя как раньше ─────────────────────────────────────
var rOldSame = evalFormulas(OLD_FORMULAS, row5243);
check('старая формула на «тыс.пог.м.» давала 22 — дефект воспроизводится',
  rOldSame['1076'] === '22', rOldSame['1076']);

var rowSht = {
  'Вид сырья': 'MW308 110 x 110 OUT', 'Длина, м': '110',
  'Срок изготовления': '14.09.2026', 'Ед.изм.': 'шт', 'Заказанное количество': 200
};
var rSht = evalFormulas(NEW_FORMULAS, rowSht);
check('шт: 200 остаётся 200', rSht['1076'] === '200', rSht['1076']);
check('шт: «Заказано в метрах» пусто', rSht['136894'] === '', JSON.stringify(rSht['136894']));

var rowPog = {
  'Вид сырья': 'MR194 60 x 300 OUT', 'Длина, м': '300',
  'Срок изготовления': '11.09.2026', 'Ед.изм.': 'пог. м', 'Заказанное количество': 6100
};
var rPog = evalFormulas(NEW_FORMULAS, rowPog);
check('пог. м: 6100/300 → 21 шт (ceil)', rPog['1076'] === '21', rPog['1076']);
check('пог. м: «Заказано в метрах» = 6100', rPog['136894'] === '6100', rPog['136894']);

var rowPogNoDot = Object.assign({}, rowPog, {'Ед.изм.': 'пог м'});
check('пог м (без точек) — та же единица → 21 шт',
  evalFormulas(NEW_FORMULAS, rowPogNoDot)['1076'] === '21',
  evalFormulas(NEW_FORMULAS, rowPogNoDot)['1076']);

var rowNosrok = Object.assign({}, row5243, {'Срок изготовления': ''});
check('пустой «Срок изготовления» — строка не считается (пусто)',
  evalFormulas(NEW_FORMULAS, rowNosrok)['1076'] === '', evalFormulas(NEW_FORMULAS, rowNosrok)['1076']);

var rowNoLen = Object.assign({}, row5243, {'Вид сырья': 'Фольга', 'Ед.изм.': 'шт', 'Заказанное количество': 200});
check('в «Виде сырья» нет «N x M» и единица шт — делитель 1, значение как есть',
  evalFormulas(NEW_FORMULAS, rowNoLen)['1076'] === '200',
  evalFormulas(NEW_FORMULAS, rowNoLen)['1076']);

// ── Формулы в скрипте-правильщике базы совпадают со спецификацией ────────────
// docs/scripts/fix_4906_unit_regex.js — то, чем правится база; тест не даёт им
// разъехаться.
var scriptPath = path.join(__dirname, '..', 'docs', 'scripts', 'fix_4906_unit_regex.js');
if (fs.existsSync(scriptPath)) {
  var src = fs.readFileSync(scriptPath, 'utf8');
  check('скрипт fix_4906_unit_regex.js: выражение 1076 = NEW',
    src.indexOf(F1076_NEW) >= 0, 'нет F1076_NEW');
  check('скрипт fix_4906_unit_regex.js: выражение 136894 = NEW',
    src.indexOf(F136894_NEW) >= 0, 'нет F136894_NEW');
  check('скрипт fix_4906_unit_regex.js: правит все три настройки (66419, 130866, 743249)',
    src.indexOf('66419') >= 0 && src.indexOf('130866') >= 0 && src.indexOf('743249') >= 0);
} else {
  check('скрипт fix_4906_unit_regex.js существует', false, scriptPath);
}

console.log('\n' + passed + ' passed, ' + failed + ' failed');
