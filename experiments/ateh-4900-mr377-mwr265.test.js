//
// Номенклатура MR377/MWR265 — один продукт: из 1С приходит как «MR377/MWR265»,
// в заказах клиентов — как попало («MR377 ...», «MWR265 ...», «Образец MR377»,
// другой порядок, регистр, разделители). Отдельные записи MR377 и MWR265 из
// справочника удалены: формула обязана превращать ЛЮБУЮ строку с упоминанием
// MR377 или MWR265 в точное имя оставшейся записи «MR377/MWR265» — иначе
// резолвинг ссылок при импорте создаёт запись-огрызок заново.
//
// Формула — данные (поле 273 записи 66419 таблицы 269), не код репозитория, so
// проверяемое артефакт — experiments/ateh-4900-upload-66419-formula.txt: он и
// накатывается в настройку. Тест прогоняет формулу тем же механизмом, что
// templates/upload.html: подстановка «[Вид сырья]» → escapeFormulaValue → eval.

const { readFileSync } = require('fs');
const { join } = require('path');

const FORMULA_FILE = join(__dirname, 'ateh-4900-upload-66419-formula.txt');

// Копия escapeFormulaValue из templates/upload.html (issue #3440): значение
// ячейки подставляется внутрь строкового литерала — спецсимволы экранируем.
function escapeFormulaValue(v) {
  return String(v === undefined || v === null ? '' : v)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/`/g, '\\`')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .split(String.fromCharCode(0x2028)).join("\\u2028")
    .split(String.fromCharCode(0x2029)).join("\\u2029")
}

// Копия механизма подстановки из templates/upload.html (строки ~1332):
// «[Имя колонки]» в формуле заменяется значением ячейки этой колонки.
function runFormula(formula, vidSyrya) {
  const expr = formula.replace(/\[(.+?)\]/mug, ($1, $2) => {
    if ($2 === 'Вид сырья') return escapeFormulaValue(vidSyrya);
    return '[' + $2 + ']';
  });
  return eval(expr);
}

